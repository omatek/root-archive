import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {Marked} from 'marked';

export const POLICIES = [
  ['privacy-notice', 'Privacy Notice'], ['terms-of-use', 'Terms of Use'],
  ['content-and-copyright-policy', 'Content and Copyright Policy'],
  ['takedown-and-dispute-procedure', 'Takedown and Dispute Procedure'],
  ['contributor-declaration', 'Contributor Declaration'],
  ['independence-statement', 'Independence and Non-Affiliation Statement'],
];
const root = fileURLToPath(new URL('../', import.meta.url));
const escape = value => value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const markdown = new Marked({gfm:true, renderer:{html({text}) {return escape(text);}}});
export function policyLinks(prefix = '') {
  return POLICIES.map(([slug,title]) => `<a href="${prefix}${slug}.html">${title}</a>`).join('');
}
export function publishedLinks(source) {
  return source.replace(/\]\(root-archive-([a-z-]+)\.md(#[^)]*)?\)/g, (match,slug,fragment='') => {
    if (!POLICIES.some(([id]) => id === slug)) throw new Error(`Internal document must not become a public policy link: ${slug}`);
    return `](/policies/${slug}.html${fragment})`;
  });
}
export async function policyArtifacts() {
  const artifacts = new Map();
  for (const [slug,title] of POLICIES) {
    const source = await readFile(resolve(root,`docs/legal/root-archive-${slug}.md`),'utf8');
    const content = await markdown.parse(publishedLinks(source));
    artifacts.set(`site/policies/${slug}.html`, `<!doctype html>
<!-- Generated by node scripts/build-policies.mjs from docs/legal; edit the Markdown. -->
<html lang="en">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="${source.includes('**BLOCKED') ? 'noindex, nofollow' : 'index, follow'}">
  <title>${escape(title)} — root/archive</title>
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../styles.css?v=legal-1">
</head>
<body>
  <a class="skip-link" href="#main-content">Skip to content</a>
  <header class="masthead"><div class="shell masthead-inner">
    <a class="wordmark" href="../" aria-label="root/archive home"><span class="wordmark-root">root</span><span class="wordmark-slash" aria-hidden="true">/</span><span class="wordmark-product">archive</span></a>
    <nav aria-label="Main navigation"><a href="../?view=about">About root</a></nav>
  </div></header>
  <main id="main-content" class="shell" tabindex="-1"><article class="policy-content">
    <a class="back-link" href="../">← Course directory</a>
${content}
  </article></main>
  <footer class="site-footer"><div class="shell footer-inner">
    <div class="footer-signature"><strong>A project by root.</strong></div>
    <nav class="footer-links" aria-label="Policies">${policyLinks()}</nav>
  </div></footer>
</body></html>
`);
    if (slug === 'privacy-notice') {
      const consent = /^## Contributor privacy and transfer consent\n\n\*\*Consent version\*\* ([^\n]+)\n\n([^\n]+)$/m.exec(source);
      if (!consent) throw new Error('Privacy Notice must include the versioned contributor consent text');
      const [, version, text] = consent;
      artifacts.set('site/js/contributor-privacy-consent.mjs', `// Generated from the Privacy Notice. Update the version when the consent text changes.\nexport const CONTRIBUTOR_PRIVACY_CONSENT = Object.freeze(${JSON.stringify({version, text},null,2)});\n`);
    }
    if (slug === 'contributor-declaration') {
      const version = /^\*\*Declaration version\*\* (.+)$/m.exec(source)?.[1];
      if (!version) throw new Error('Contributor declaration must have an explicit version');
      const text = publishedLinks(source.slice(source.indexOf(version)+version.length).trim());
      artifacts.set('site/js/contributor-authorization.mjs', `// Generated from the reconciled canonical Contributor Declaration.\n// Regenerate with node scripts/build-policies.mjs; change the version when wording changes.\nexport const CONTRIBUTOR_AUTHORIZATION = Object.freeze(${JSON.stringify({version,language:'en',text},null,2)});\n`);
    }
  }
  return artifacts;
}
export async function buildPolicies({check = false} = {}) {
  for (const [path,content] of await policyArtifacts()) {
    const destination = resolve(root,path);
    if (check) {
      if (await readFile(destination,'utf8') !== content) throw new Error(`Stale policy artifact: ${path}`);
    } else {
      await mkdir(resolve(destination,'..'),{recursive:true});
      await writeFile(destination,content);
    }
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPolicies({check:process.argv.includes('--check')});
}
